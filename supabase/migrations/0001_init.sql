-- ============================================================================
-- Transaction webhook service: schema + serverless processing pipeline
--
-- Run this once in the Supabase SQL editor (Dashboard -> SQL Editor -> New query)
-- AFTER editing the two vault.create_secret(...) lines in section 3.
--
-- How processing works on Vercel (which cannot run long-lived background workers):
--   1. POST /v1/webhooks/transactions inserts a row (status = PROCESSING) and returns 202.
--   2. The AFTER INSERT trigger below makes an *asynchronous* HTTP call (pg_net) to
--      POST https://<your-app>.vercel.app/v1/internal/process, which sleeps 30s and
--      flips the row to PROCESSED. The insert itself is never slowed down.
--   3. A pg_cron job re-sends any row still PROCESSING after 2 minutes, so a lost
--      request, a crashed function or a deploy in the middle of processing is retried
--      until the transaction is processed. The app's conditional UPDATE guarantees it is
--      still processed exactly once.
-- ============================================================================

-- 1. Extensions -------------------------------------------------------------
create extension if not exists pg_net with schema extensions;
create extension if not exists pg_cron;

-- 2. Table ------------------------------------------------------------------
create table if not exists public.transactions (
    id                  bigint generated by default as identity primary key,
    transaction_id      varchar(128) not null,
    source_account      varchar(128) not null,
    destination_account varchar(128) not null,
    amount              numeric(18, 2) not null check (amount > 0),
    currency            varchar(3) not null,
    status              varchar(16) not null default 'PROCESSING'
                        check (status in ('PROCESSING', 'PROCESSED')),
    created_at          timestamptz not null default now(),
    processed_at        timestamptz,
    processing_attempts integer not null default 0,
    last_error          text,
    constraint transactions_transaction_id_key unique (transaction_id)   -- idempotency
);

create index if not exists ix_transactions_status_created_at
    on public.transactions (status, created_at);

-- The app connects as the postgres role (bypasses RLS). Enabling RLS with no policies
-- hides the table from the public REST API / anon key.
alter table public.transactions enable row level security;

-- 3. Secrets (edit these two values!) -----------------------------------------
-- processor_url   : your deployed app + /v1/internal/process
-- internal_secret : must equal the INTERNAL_SECRET env var on Vercel
select vault.create_secret('https://YOUR-APP.vercel.app/v1/internal/process', 'processor_url');
select vault.create_secret('change-me', 'internal_secret');

-- To change them later:
--   update vault.secrets set secret = 'https://new-url/v1/internal/process' where name = 'processor_url';

-- 4. Helper: ask the app to process one transaction (async, never blocks) -----
create or replace function public.request_transaction_processing(p_transaction_id text)
returns bigint
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
    v_url    text;
    v_secret text;
begin
    select decrypted_secret into v_url    from vault.decrypted_secrets where name = 'processor_url';
    select decrypted_secret into v_secret from vault.decrypted_secrets where name = 'internal_secret';

    return net.http_post(
        url                  := v_url,
        body                 := jsonb_build_object('transaction_id', p_transaction_id),
        headers              := jsonb_build_object(
                                    'Content-Type', 'application/json',
                                    'X-Internal-Secret', v_secret),
        timeout_milliseconds := 45000   -- processing takes ~30s; keep the request open
    );
end;
$$;

-- 5. Trigger: fire on every new transaction ------------------------------------
create or replace function public.on_transaction_inserted()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    perform public.request_transaction_processing(new.transaction_id);
    return new;
end;
$$;

drop trigger if exists trg_transaction_inserted on public.transactions;
create trigger trg_transaction_inserted
    after insert on public.transactions
    for each row execute function public.on_transaction_inserted();

-- 6. Safety net: retry anything stuck in PROCESSING -----------------------------
create or replace function public.retry_stuck_transactions()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    v_row   record;
    v_count integer := 0;
begin
    for v_row in
        select transaction_id
        from public.transactions
        where status = 'PROCESSING'
          and created_at < now() - interval '2 minutes'
          and processing_attempts < 20
        order by created_at
        limit 100
    loop
        perform public.request_transaction_processing(v_row.transaction_id);
        v_count := v_count + 1;
    end loop;
    return v_count;
end;
$$;

select cron.unschedule(jobid) from cron.job where jobname = 'retry-stuck-transactions';
select cron.schedule('retry-stuck-transactions', '* * * * *', $$ select public.retry_stuck_transactions(); $$);

